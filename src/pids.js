export function calcPid(pid, bytes){
  const def = PIDS[pid];
  if(!def || !bytes || bytes.length < Math.min(def.b,2)) return null;
  try{
    const v = def.f(bytes);
    return (typeof v==='number' && isFinite(v)) ? Math.round(v*1000)/1000 : null;
  }catch(_){ return null; }
}

/* ถอด bitmask จาก 0100/0120/0140/0160 → รายชื่อ PID ที่รถรองรับ */
export function decodeSupported(basePid, bytes){
  const out=[], start=parseInt(basePid.slice(2),16);
  for(let i=0;i<4 && i<bytes.length;i++)
    for(let bit=7;bit>=0;bit--)
      if(bytes[i] & (1<<bit))
        out.push('01'+(start+i*8+(7-bit)+1).toString(16).toUpperCase().padStart(2,'0'));
  return out;
}