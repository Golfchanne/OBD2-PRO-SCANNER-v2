export function describeDtc(code){
  return {
    code,
    desc: DTC_DB[code] || (code[1]==='1'
      ? 'รหัสเฉพาะผู้ผลิต — ไม่มีคำอธิบายมาตรฐาน โปรดเทียบคู่มือซ่อมของยี่ห้อนั้น'
      : 'ไม่พบคำอธิบายในฐานข้อมูล — เพิ่มได้ที่ DTC_DB'),
    system: systemOf(code),
    known: !!DTC_DB[code],
  };
}