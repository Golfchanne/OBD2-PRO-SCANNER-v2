const LETTERS = ['P','C','B','U'];

export function decodeDtc(a,b){
  if(a===0 && b===0) return null;
  const L = LETTERS[(a>>6)&0x03];
  const d1=(a>>4)&0x03, d2=(a&0x0F).toString(16).toUpperCase();
  const d3=((b>>4)&0x0F).toString(16).toUpperCase(), d4=(b&0x0F).toString(16).toUpperCase();
  return `${L}${d1}${d2}${d3}${d4}`;
}

export function systemOf(code){
  const L=code[0], n=parseInt(code.slice(2,4),16);
  if(L==='P'){
    if(code[1]==='1') return 'เฉพาะผู้ผลิต — ต้องเทียบคู่มือยี่ห้อนั้น';
    if(n<=0x09) return 'ระบบวัดปริมาณเชื้อเพลิงและอากาศ';
    if(n<=0x1F) return 'ระบบเชื้อเพลิง/อากาศ และเซ็นเซอร์ออกซิเจน';
    if(n<=0x2F) return 'ระบบเชื้อเพลิงและอากาศ (วงจรเสริม)';
    if(n<=0x39) return 'ระบบจุดระเบิด / การจุดระเบิดผิดจังหวะ';
    if(n<=0x4F) return 'ระบบควบคุมไอเสีย (EGR, EVAP, แคตตาไลติก)';
    if(n<=0x5F) return 'ระบบควบคุมความเร็วและรอบเดินเบา';
    if(n<=0x6F) return 'วงจรสัญญาณออก / คอมพิวเตอร์ ECU';
    if(n<=0x8F) return 'ระบบเกียร์';
    return 'ระบบส่งกำลัง (อื่น ๆ)';
  }
  if(L==='C') return 'ช่วงล่าง / เบรก / ABS / พวงมาลัย';
  if(L==='B') return 'ตัวถังและอุปกรณ์ภายใน (ถุงลม แอร์ ไฟ)';
  return 'เครือข่ายสื่อสาร CAN Bus';
}

